-- Schema SYLT auf PDBORCL, Präfix SY_. Werkbuch Abschnitt 10, freigegeben am 28.10.2026 (F33–F45 „alle A“).
--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter der App
-- übergeht genau diese Meldung. In SQL Developer als Skript ausführen (F5); die Meldungen bei einem zweiten
-- Lauf sind dann harmlos. Dieses Skript löscht nichts.
--
-- Hauskonvention: ID aus Sequence + Trigger, nie GENERATED AS IDENTITY. Je Spalte eine Zeile, damit der
-- Einrichter fehlende Spalten erkennen und nachtragen kann. Geometrien in UTM 32N (SRID 25832, Meter, wie die
-- Szene, F35 A); die Sichten in 03_sichten.sql geben sie für QGIS in 8307 (WGS 84). Szenenmeter: x nach Osten,
-- z nach Süden, Ursprung am Quermarkenfeuer (E 457 600, N 6 091 170); Ost = x + 457 600, Nord = 6 091 170 − z.
-- Szenenzeit (F34 A): SZENE_MS = Millisekunden seit 1970 wie die Uhr der App, dazu SZENE_ZEIT als
-- TIMESTAMP WITH TIME ZONE in Europe/Berlin (Sylt spielt nach 1582, kein julianischer Sonderweg).
-- 25 Tabellen in sieben Themen: Betrieb, Quellen, Gelände, Küste (Sturmfluten, Abbrüche, Kanten, Findlinge,
-- Vorspülungen, Serien), Wetter und Türme, Regie und Kamera, Packages.
-- =====================================================================================================


-- -----------------------------------------------------------------------------------------------------
-- SY_SCHEMA: Stand des Schemas, eine Zeile je Ausbaustufe; der Einrichter liest hier, was schon da ist. Phase 16 =
-- 1.
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE SY_SCHEMA (
  VERSION      NUMBER(4) NOT NULL,
  EINGERICHTET TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  APP_VERSION  VARCHAR2(20 CHAR) NOT NULL,
  TEXT         VARCHAR2(400 CHAR),
  CONSTRAINT SY_SCHEMA_PK PRIMARY KEY (VERSION)
);


-- -----------------------------------------------------------------------------------------------------
-- SY_QUELLE: Quellen zum Vorbild (Werkbuch Abschnitte 2 und 16), Daten (DGM1, BAW, Pegel) und Recherchen zu
-- Sturmfluten und Vorspülungen.
-- -----------------------------------------------------------------------------------------------------
CREATE SEQUENCE SY_QUELLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SY_QUELLE (
  ID        NUMBER(10) NOT NULL,
  KURZ      VARCHAR2(30 CHAR) NOT NULL,
  TITEL     VARCHAR2(300 CHAR) NOT NULL,
  URL       VARCHAR2(400 CHAR),
  ART       VARCHAR2(8) NOT NULL,
  ABGERUFEN DATE,
  BEMERKUNG VARCHAR2(400 CHAR),
  HERKUNFT  VARCHAR2(12) DEFAULT 'EIGEN' NOT NULL,
  ANGELEGT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  GEAENDERT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT SY_QUELLE_PK PRIMARY KEY (ID),
  CONSTRAINT SY_QUELLE_UK UNIQUE (KURZ),
  CONSTRAINT SY_QUELLE_ART_CK CHECK (ART IN ('WEB','BUCH','ARTIKEL','DATEN','MESSUNG')),
  CONSTRAINT SY_QUELLE_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
);

CREATE OR REPLACE TRIGGER SY_QUELLE_BIU
BEFORE INSERT OR UPDATE ON SY_QUELLE
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.ID IS NULL THEN
      :NEW.ID := SY_QUELLE_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
/


